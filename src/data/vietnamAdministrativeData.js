// Helper tra cứu sáp nhập đơn vị hành chính 2 cấp và sinh gợi ý địa chỉ mới
export function findAdministrativeMerger({ city, district, ward, street }) {
  if (!city && !ward) return null;
  const cleanCity = (city || '').toLowerCase().trim();
  const cleanDistrict = (district || '').toLowerCase().trim();
  const cleanWard = (ward || '').toLowerCase().trim();

  const match = VIETNAM_ADMINISTRATIVE_MERGERS.find(m => {
    // 1. Kiểm tra Tỉnh/Thành
    const matchCity = !cleanCity || 
      m.city.toLowerCase() === cleanCity || 
      cleanCity.includes(m.city.toLowerCase()) || 
      m.city.toLowerCase().includes(cleanCity);
    if (!matchCity) return false;

    // 2. Kiểm tra Quận/Huyện (nếu có)
    if (cleanDistrict && m.district) {
      const cleanOldD = m.district.toLowerCase().replace(/^(quận|huyện|thị xã|thành phố)\s+/i, '').trim();
      const cleanD = cleanDistrict.replace(/^(quận|huyện|thị xã|thành phố)\s+/i, '').trim();
      const matchDistrict = cleanOldD === cleanD || cleanDistrict.includes(cleanOldD) || m.district.toLowerCase().includes(cleanDistrict);
      if (!matchDistrict) return false;
    }

    // 3. Kiểm tra Phường/Xã
    if (m.oldWard && cleanWard) {
      const cleanOldW = m.oldWard.toLowerCase().replace(/^(phường|xã|thị trấn)\s+/i, '').trim();
      const cleanW = cleanWard.replace(/^(phường|xã|thị trấn)\s+/i, '').trim();
      if (cleanOldW === cleanW || cleanWard.includes(cleanOldW) || cleanOldW.includes(cleanW)) {
        return true;
      }
    }

    // 4. Fallback theo tên đường phố tiêu biểu (chỉ áp dụng khi người dùng chưa chọn Phường/Xã cụ thể)
    if (!cleanWard && street && m.sampleStreets && m.sampleStreets.length > 0) {
      const cleanSt = street.toLowerCase().replace(/^(đường|phố)\s+/i, '').trim();
      const matchSt = m.sampleStreets.some(s => s.toLowerCase().includes(cleanSt) || cleanSt.includes(s.toLowerCase()));
      if (matchSt && (!cleanDistrict || m.district.toLowerCase().includes(cleanDistrict))) {
        return true;
      }
    }

    return false;
  });

  if (!match) return null;

  const streetClean = street ? street.replace(/^(đường|phố)\s+/i, '').trim() : '';
  const streetPart = streetClean ? `Đường ${streetClean}` : '';

  const oldParts = [
    streetPart,
    ward || match.oldWard,
    district || match.district,
    city || match.city
  ].filter(Boolean);
  const oldAddress = oldParts.join(', ');

  const targetDistrict = match.newDistrict || match.district || district;
  const targetCity = match.newCity || match.city || city;

  const newParts = [
    streetPart,
    match.newWard,
    targetDistrict,
    targetCity
  ].filter(Boolean);
  const newAddress = newParts.join(', ');

  return {
    ...match,
    hasMerger: true,
    oldCity: city || match.city,
    oldDistrict: district || match.district,
    oldWard: ward || match.oldWard,
    newCity: targetCity,
    newDistrict: targetDistrict,
    newWard: match.newWard,
    lat: match.lat,
    lng: match.lng,
    google_place_id: match.google_place_id,
    oldAddress,
    newAddress,
    highlightText: match.newWard,
    suggestionLabel: 'Địa chỉ do hệ thống gợi ý'
  };
}
